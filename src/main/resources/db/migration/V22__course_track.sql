-- track: رشته‌ای که درس مخصوص آن است («ریاضی»، «تجربی»، «انسانی»). خالی (NULL) = درس مشترک: به همه‌ی دانش‌آموزان
-- پایه نشان داده می‌شود. خالی «همهٔ رشته‌ها» نیست؛ دانش‌آموزِ بدون رشته هم فقط درس‌های مشترک را می‌بیند.
-- همه‌ی درس‌های موجود خالی (مشترک) می‌مانند؛ مقدارها را مثل بقیه‌ی کاتالوگ، مهاجرتِ داده می‌گذارد.

alter table academic.courses add column track varchar(16);
alter table academic.courses add constraint ck_courses_track
    check (track is null or track in ('ریاضی', 'تجربی', 'انسانی'));
