-- جدا از iam.invite_tokens: عمرِ کوتاه (یک ساعت)، یک‌بارمصرف، و فقط هشِ توکن در پایگاه داده
-- نگه داشته می‌شود (مقدارِ خامِ توکن فقط در ایمیلِ کاربر است).
create table iam.password_reset_tokens (
    id         bigint generated by default as identity,
    user_id    bigint                   not null,
    token_hash varchar(64)              not null unique,
    created_at timestamp(6) with time zone not null,
    expires_at timestamp(6) with time zone not null,
    used_at    timestamp(6) with time zone,
    primary key (id)
);

create index password_reset_tokens_user_idx on iam.password_reset_tokens (user_id);
