-- هیچ کلیدِ خارجی بین ماژولی نیست: کلاس و دانش‌آموز با شناسه‌ی مات ارجاع می‌شوند
-- (مرز ماژول). day تاریخ میلادیِ ISO است؛ نمایشِ شمسی با UI.

-- rolls: ردیفِ «حضور و غیابِ این کلاس در این روز گرفته شد». بدونِ آن کلاس «ثبت نشده»
-- است، که با «هیچ‌کس غایب نبود» یکی نیست.
create table attendance.rolls (
    id bigint generated by default as identity,
    school_id bigint not null,
    class_id bigint not null,
    day date not null,
    taken_by_user_id bigint,
    taken_at timestamptz not null default now(),
    primary key (id),
    unique (class_id, day)
);
create index rolls_school_day_idx on attendance.rolls (school_id, day);

-- marks: فقط استثناها ذخیره می‌شوند؛ دانش‌آموزِ یک roll بدونِ mark حاضر است.
-- excused فقط برای ABSENT معنا دارد.
create table attendance.marks (
    id bigint generated by default as identity,
    school_id bigint not null,
    class_id bigint not null,
    day date not null,
    student_id bigint not null,
    status varchar(8) not null check (status in ('ABSENT', 'LATE')),
    excused boolean not null default false,
    note varchar(255),
    marked_by_user_id bigint,
    marked_at timestamptz not null default now(),
    primary key (id),
    unique (class_id, day, student_id)
);
create index marks_school_day_idx on attendance.marks (school_id, day);
create index marks_student_day_idx on attendance.marks (student_id, day);

-- excuses: عذرخواهیِ ولی برای یک غیبت (فاز ۳؛ جدول از همین حالا ساخته می‌شود تا
-- مهاجرتِ دیگری لازم نباشد، هنوز هیچ کدی از آن استفاده نمی‌کند). برای هر
-- (دانش‌آموز، روز) یک عذر.
create table attendance.excuses (
    id bigint generated by default as identity,
    school_id bigint not null,
    class_id bigint not null,
    day date not null,
    student_id bigint not null,
    note varchar(500) not null,
    submitted_by_user_id bigint not null,
    submitted_at timestamptz not null default now(),
    status varchar(16) not null default 'PENDING' check (status in ('PENDING', 'APPROVED', 'REJECTED')),
    decided_by_user_id bigint,
    decided_at timestamptz,
    primary key (id),
    unique (student_id, day)
);
create index excuses_school_day_idx on attendance.excuses (school_id, day);
