-- school.calendar_entries: روزهای خاصِ هر مدرسه. CLOSED = روز تعطیل (حضور و غیاب
-- برای آن روز ثبت نمی‌شود)؛ EVENT برای «برنامه‌ی سالانه‌ی» بعدی کنار گذاشته شده و
-- هنوز کسی از آن استفاده نمی‌کند. یک روز می‌تواند چند ردیف داشته باشد، پس یکتایی
-- روی (school_id, day, ...) نیست. day تاریخ میلادیِ ISO است؛ نمایشِ شمسی با UI.
create table school.calendar_entries (
    id bigint generated by default as identity,
    school_id bigint not null references school.schools (id),
    day date not null,
    kind varchar(16) not null check (kind in ('CLOSED', 'EVENT')),
    title varchar(128) not null,
    created_at timestamptz not null default now(),
    primary key (id)
);
create index calendar_entries_school_day_idx
    on school.calendar_entries (school_id, day);
