-- ---------------------------------------------------------------------
-- نمره‌ها به تفکیک درس (openspec/changes/grades-by-course.md)
-- ---------------------------------------------------------------------
-- academic.courses: فهرست سراسری درس‌ها به تفکیک پایه، مشترک بین همه‌ی
-- مدرسه‌ها (بدون school_id). در این فاز فقط خواندنی است و ردیف‌ها را
-- اپراتور پلتفرم با مهاجرت داده/اسکریپت SQL مدیریت می‌کند؛ هیچ ردیفی اینجا
-- seed نمی‌شود چون فهرست درس‌های هر پایه تصمیم محصول است.
--
-- academic.grades.course_id: خالی یعنی «نمرهٔ کل» (همه‌ی نمره‌های موجود).

create table academic.courses (
    grade_level integer not null check (grade_level between 1 and 12),
    id bigint generated by default as identity,
    name varchar(128) not null,
    primary key (id),
    unique (grade_level, name)
);

alter table academic.grades
    add column course_id bigint references academic.courses (id) on delete restrict;

-- کلید یکتای قبلی (student, class, year, term) باید برود: با درس، یک دانش‌آموز
-- در یک نوبت چند نمره (هر درس یکی) دارد. نامِ constraint در دیتابیس‌هایی که
-- از قبل با ddl-auto=update ساخته شده‌اند (baseline-on-migrate، V1 رد می‌شود)
-- با نامِ تولیدی V1 فرق دارد، پس از روی ستون‌هایش پیدا می‌شود نه از روی نام.
do $$
declare
    existing record;
begin
    for existing in
        select con.conname
        from pg_constraint con
                 join pg_class rel on rel.oid = con.conrelid
                 join pg_namespace ns on ns.oid = rel.relnamespace
        where ns.nspname = 'academic'
          and rel.relname = 'grades'
          and con.contype = 'u'
          and (select array_agg(att.attname::text order by att.attname)
               from unnest(con.conkey) as key (attnum)
                        join pg_attribute att on att.attrelid = rel.oid and att.attnum = key.attnum)
              = array ['academic_year', 'class_id', 'student_id', 'term']
        loop
            execute format('alter table academic.grades drop constraint %I', existing.conname);
        end loop;
end
$$;

-- unique روی ستون nullable چند «نمرهٔ کل» را هم‌زمان مجاز می‌کرد (NULL ها
-- متمایزند)، پس دو ایندکس جزئی: یکی برای نمرهٔ کل، یکی برای هر درس.
create unique index grades_overall_unique
    on academic.grades (student_id, class_id, academic_year, term)
    where course_id is null;

create unique index grades_course_unique
    on academic.grades (student_id, class_id, academic_year, term, course_id)
    where course_id is not null;
