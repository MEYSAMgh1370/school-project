-- سال تحصیلی (openspec/changes/academic-year.md، فاز ۰)
-- ---------------------------------------------------------------------
-- school.academic_years: فهرست سراسریِ سال‌های تحصیلی، مشترک بین همه‌ی مدرسه‌ها
-- (بدون school_id). هیچ اپراتوری سال نمی‌سازد: خودِ برنامه هر سال، در تاریخِ
-- شمسیِ تعیین‌شده در کانفیگ (roshdeandishe.academic-year.start-month/start-day)،
-- سالِ تحصیلیِ تازه را می‌سازد و اینجا ذخیره می‌کند (school.internal.
-- AcademicYearProvisioner) - مثلاً در ۱ مرداد ۱۴۰۵ سالِ «1405-1406». code همان
-- شکل متداولِ نمره‌هاست («1404-1405»، رقم ASCII) و start_year برای ترتیب‌دهی
-- و یکتایی است. سال تاریخ شروع/پایان ندارد: شروع و پایانِ هر سال را مدیرِ
-- مدرسه با انتخابِ سال جاری تعیین می‌کند.
--
-- school.schools.current_academic_year_id: «سال تحصیلی جاریِ» هر مدرسه که مدیرِ
-- همان مدرسه از همین فهرست انتخاب می‌کند. خالی یعنی هنوز انتخاب نشده (همه‌ی
-- مدرسه‌های موجود)؛ هیچ سالی برای مدرسه‌ی موجود حدس زده نمی‌شود.

create table school.academic_years (
    id bigint generated by default as identity,
    code varchar(16) not null,
    start_year integer not null check (start_year between 1300 and 1700),
    primary key (id),
    unique (code),
    unique (start_year)
);

alter table school.schools
    add column current_academic_year_id bigint references school.academic_years (id) on delete restrict;

-- فقط سالِ پایه: نمره‌های موجود (و تست‌ها) سالِ «1404-1405» را به کار برده‌اند.
-- سال‌های بعدی را AcademicYearProvisioner خودکار می‌سازد (از همین سال به بعد، بدون
-- حفره).
insert into school.academic_years (code, start_year)
values ('1404-1405', 1404);
