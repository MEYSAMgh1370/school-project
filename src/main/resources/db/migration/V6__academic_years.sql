-- school.academic_years: فهرست سراسریِ سال‌های تحصیلی، مشترک بین همه‌ی مدرسه‌ها
-- (بدون school_id) و فقط‌خواندنی در برنامه؛ ردیف‌ها را اپراتور پلتفرم با مهاجرت
-- داده مدیریت می‌کند - مثل کاتالوگ درس‌ها (academic.courses). code همان شکل
-- متداول نمره‌هاست («1404-1405»، رقم ASCII) و start_year برای ترتیب‌دهی است.
--
-- school.schools.current_academic_year_id: «سال تحصیلی جاریِ» هر مدرسه که مدیرِ
-- همان مدرسه از همین فهرست انتخاب می‌کند. خالی یعنی هنوز انتخاب نشده (همه‌ی
-- مدرسه‌های موجود)؛ هیچ سالی برای مدرسه‌ی موجود حدس زده نمی‌شود.

create table school.academic_years (
    id bigint generated by default as identity,
    code varchar(16) not null,
    start_year integer not null check (start_year between 1300 and 1700),
    primary key (id),
    unique (code),
    unique (start_year)
);

alter table school.schools
    add column current_academic_year_id bigint references school.academic_years (id) on delete restrict;

-- سال‌های اولیه‌ی فهرست (داده‌ی تقویمی، نه تصمیم محصول). سال‌های بعدی را اپراتور
-- با یک مهاجرت داده‌ی تازه اضافه می‌کند.
insert into school.academic_years (code, start_year)
values ('1404-1405', 1404),
       ('1405-1406', 1405);
