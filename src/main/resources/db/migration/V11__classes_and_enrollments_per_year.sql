-- ---------------------------------------------------------------------
-- کلاس و ثبت‌نام به‌تفکیک سال تحصیلی و ارتقای پایه (openspec/changes/academic-year.md، فاز ۳)
-- ---------------------------------------------------------------------
-- classes.academic_year: کدِ canonical سال («1405-1406») مثل نمره و شهریه، بدون کلیدِ خارجی (فهرستِ
-- سال‌ها در ماژول school است). خالی (NULL) = «به سالی نسبت داده نشده»: همه‌ی کلاس‌های موجود و کلاس‌های
-- مدرسه‌ای که سالِ جاری ندارد؛ ادمین با یک اقدامِ صریح آن‌ها را به یک سال نسبت می‌دهد، هیچ سالی حدس زده نمی‌شود.
--
-- students.status / class_id: class_id همان «ثبت‌نامِ جاری» است که نمره، پیشخوان، ربات بله و ... می‌خوانند؛
-- برای دانش‌آموزِ PENDING (ارتقا یافته، کلاس هنوز انتخاب نشده) و GRADUATED/LEFT تهی است.

alter table academic.classes add column academic_year varchar(16);

alter table academic.students add column status varchar(16) not null default 'ACTIVE';
alter table academic.students add constraint ck_students_status
    check (status in ('ACTIVE', 'PENDING', 'GRADUATED', 'LEFT'));
alter table academic.students alter column class_id drop not null;

-- تاریخچه‌ی ثبت‌نام: یک ردیف به‌ازای (دانش‌آموز، سال). ردیفِ سالِ قبل با سالِ بعد تغییر نمی‌کند.
create table academic.enrollments (
    id bigint generated by default as identity,
    school_id bigint not null,
    student_id bigint not null references academic.students (id),
    academic_year varchar(16) not null,
    class_id bigint references academic.classes (id),
    grade_level integer not null,
    status varchar(16) not null check (status in ('ENROLLED', 'PENDING')),
    promotion_run_id bigint,
    created_at timestamp(6) with time zone not null,
    primary key (id),
    constraint uq_enrollments_student_year unique (student_id, academic_year)
);

create index ix_enrollments_school_year on academic.enrollments (school_id, academic_year);
create index ix_enrollments_class on academic.enrollments (class_id);

-- هر بار اجرای ارتقا یک «اجرا» است تا بشود آن را برگرداند (undo)؛ وضعیتِ قبلیِ هر دانش‌آموز نگه‌داری می‌شود.
create table academic.promotion_runs (
    id bigint generated by default as identity,
    school_id bigint not null,
    from_year varchar(16) not null,
    to_year varchar(16) not null,
    mode varchar(8) not null check (mode in ('MANUAL', 'AUTO')),
    created_by_user_id bigint,
    created_at timestamp(6) with time zone not null,
    undone_at timestamp(6) with time zone,
    primary key (id)
);

create index ix_promotion_runs_school on academic.promotion_runs (school_id, to_year);

create table academic.promotion_run_students (
    id bigint generated by default as identity,
    run_id bigint not null references academic.promotion_runs (id),
    student_id bigint not null references academic.students (id),
    outcome varchar(8) not null check (outcome in ('PROMOTE', 'REPEAT', 'GRADUATE', 'LEAVE')),
    previous_status varchar(16) not null,
    previous_class_id bigint,
    membership_deactivated boolean not null default false,
    primary key (id),
    constraint uq_promotion_run_student unique (run_id, student_id)
);

-- ارتقای خودکار هنگام تعویضِ سالِ جاری؛ پیش‌فرض خاموش (مدرسه خودش روشن می‌کند).
alter table school.schools add column auto_promotion boolean not null default false;
