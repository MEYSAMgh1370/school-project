-- courses.graded: درسِ کاتالوگ می‌تواند در برنامهٔ کلاسی باشد ولی در کارنامه نیاید
-- (graded = false)؛ نمره‌دادن به آن رد می‌شود و انتخابگر درسِ /grades آن را نشان
-- نمی‌دهد. پیش‌فرض true: هیچ ردیف و نمره‌ی موجودی تغییر نمی‌کند.
alter table academic.courses
    add column graded boolean not null default true;

-- activities: فعالیتِ فوق‌برنامه که فقط در برنامهٔ کلاسی می‌آید و هرگز نمره‌پذیر
-- نیست. school_id خالی = پیش‌فرضِ پلتفرم (سراسری، فقط‌خواندنی در برنامه، اپراتور با
-- مهاجرت داده مدیریت می‌کند)؛ پر = فعالیتِ همان مدرسه که مدیرش می‌سازد/تغییر نام
-- می‌دهد/حذف می‌کند. نام در هر دامنه یکتاست (دو ایندکس جزئی، مثل نمره‌ها).
create table academic.activities (
    id bigint generated by default as identity,
    school_id bigint,
    name varchar(128) not null,
    primary key (id)
);
create unique index activities_school_name_unique
    on academic.activities (school_id, name) where school_id is not null;
create unique index activities_default_name_unique
    on academic.activities (name) where school_id is null;

-- timetable_periods: زنگ‌ها را هر مدرسه برای هر سال تحصیلی تعریف می‌کند (سال یک کدِ
-- فهرستِ سراسری است، مثل grades.academic_year: academic به جدول school وصل نمی‌شود،
-- اعتبارِ کد در AcademicFacade با SchoolFacade سنجیده می‌شود). زنگ‌های یک مدرسه و سال
-- هم‌پوشانی ندارند (در لایهٔ برنامه، با پیام روشن).
create table academic.timetable_periods (
    id bigint generated by default as identity,
    school_id bigint not null,
    academic_year varchar(16) not null,
    position integer not null check (position >= 1),
    label varchar(64) not null,
    start_time time not null,
    end_time time not null,
    primary key (id),
    check (end_time > start_time),
    unique (school_id, academic_year, position)
);

-- timetable_entries: هر خانه = کلاس + زنگ (که سال را هم دارد) + روز + دقیقاً یکی از
-- درسِ کاتالوگ یا فعالیت + معلمِ اختیاری (شناسه‌ی مات کاربر iam، بدون FK بین ماژولی).
create table academic.timetable_entries (
    id bigint generated by default as identity,
    school_id bigint not null,
    class_id bigint not null references academic.classes (id) on delete cascade,
    period_id bigint not null references academic.timetable_periods (id) on delete restrict,
    weekday varchar(3) not null check (weekday in ('SAT', 'SUN', 'MON', 'TUE', 'WED')),
    course_id bigint references academic.courses (id) on delete restrict,
    activity_id bigint references academic.activities (id) on delete restrict,
    teacher_user_id bigint,
    primary key (id),
    check (num_nonnulls(course_id, activity_id) = 1)
);
-- یک موضوع برای هر کلاس در هر روز و زنگ
create unique index timetable_entries_class_slot_unique
    on academic.timetable_entries (class_id, weekday, period_id);
-- یک معلم در هر روز و زنگ حداکثر در یک کلاس (علاوه بر بررسیِ برنامه با پیام روشن)
create unique index timetable_entries_teacher_slot_unique
    on academic.timetable_entries (teacher_user_id, weekday, period_id) where teacher_user_id is not null;
