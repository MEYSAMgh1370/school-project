-- school.platform_holidays: روزهایی که مدیر پلتفرم برای یک سال تحصیلی ثبت می‌کند. هر
-- ردیف در برنامه‌ی سالانه‌ی همه‌ی مدرسه‌ها می‌آید و روز را در همه‌ی مدرسه‌ها تعطیل
-- می‌کند (SchoolFacade.isClosedDay)؛ مدرسه نمی‌تواند آن را لغو کند، پس school_id
-- ندارد. day تاریخ میلادیِ ISO است و باید در بازه‌ی همان سال باشد (۱ مهر تا ۳۱ خرداد
-- سال بعد)؛ این بازه از start_year مشتق می‌شود و در لایه‌ی facade بررسی می‌شود، نه اینجا.
-- یک روز می‌تواند چند ردیف داشته باشد، پس یکتایی روی (academic_year_id, day) نیست.
create table school.platform_holidays (
    id bigint generated by default as identity,
    academic_year_id bigint not null references school.academic_years (id),
    day date not null,
    title varchar(128) not null,
    created_at timestamptz not null default now(),
    primary key (id)
);
create index platform_holidays_year_day_idx
    on school.platform_holidays (academic_year_id, day);
-- isClosedDay فقط با روز می‌پرسد (بدون سال)
create index platform_holidays_day_idx
    on school.platform_holidays (day);
