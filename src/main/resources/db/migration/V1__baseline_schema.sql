-- رجیستری رویدادهای Spring Modulith (spring-modulith-starter-jpa). یک
-- Entityِ متعلق به خودِ فریم‌ورک است، نه این پروژه، ولی چون JPA آن را
-- مدیریت می‌کند ddl-auto=validate هم انتظارش را دارد؛ پس باید اینجا باشد.
-- در schemaی iam قرار می‌گیرد چون default_schema همان است.
create table iam.event_publication (
    completion_attempts integer not null,
    completion_date timestamp(6) with time zone,
    last_resubmission_date timestamp(6) with time zone,
    publication_date timestamp(6) with time zone,
    id uuid not null,
    event_type varchar(255),
    listener_id varchar(255),
    serialized_event varchar(255),
    status varchar(255) check ((status in ('PUBLISHED','PROCESSING','COMPLETED','FAILED','RESUBMITTED'))),
    primary key (id)
);


