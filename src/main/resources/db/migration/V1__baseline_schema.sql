-- =====================================================================
-- V1 - Baseline schema
--
-- تولید شده از روی خودِ مدل موجودیت‌ها (Hibernate schema-generation) و نه
-- دست‌نویس، تا دقیقاً همان چیزی باشد که ddl-auto=update تا امروز می‌ساخت.
-- از این پس ddl-auto روی validate است: هر تغییر در Entityها باید یک فایل
-- V<n>__... جدید داشته باشد، وگرنه اپلیکیشن در زمان بالا آمدن fail می‌کند.
--
-- نکته‌ی مهم درباره‌ی دیتابیس‌های موجود: schemaها اینجا ساخته نمی‌شوند -
-- خودِ Flyway از روی spring.flyway.schemas آن‌ها را می‌سازد (جایگزین
-- CREATE SCHEMA دستی که تا امروز لازم بود). روی دیتابیسی که از قبل با
-- ddl-auto=update ساخته شده، baseline-on-migrate=true این نسخه را رد
-- می‌کند و از V2 به بعد ادامه می‌دهد.
--
-- عمداً هیچ FOREIGN KEY ای وجود ندارد: ارجاع‌های بین‌ماژولی در این پروژه
-- Longِ مات هستند (رجوع به CLAUDE.md §4 - StudentEntity.userId،
-- ClassEntity.teacherId، StudentGuardianEntity.guardianUserId و ...) و
-- اعتبارسنجی‌شان در سطح Facade انجام می‌شود، نه در سطح DB. این فایل وضعیت
-- موجود را آینه می‌کند، نه یک بازطراحی.
-- =====================================================================


